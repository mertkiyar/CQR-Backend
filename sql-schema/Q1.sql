	'STUDENT',
	'LECTURER',
	'ADMIN'
);

CREATE TYPE GENDER_TYPE AS ENUM (
	'FEMALE',
	'MALE',
	'OTHER'
);

CREATE TYPE ACADEMIC_ROLE AS ENUM (
	'LECTURER',
	'RESEARCH_ASSISTANT',
	'DEPARTMENT_HEAD',
	'DEAN',
	'RECTOR'
);

CREATE TYPE ACADEMIC_TITLE AS ENUM (
    'PROFESSOR',
    'ASSOCIATE_PROFESSOR',
    'ASSISTANT_PROFESSOR',
    'DOCTOR_LECTURER',
    'LECTURER',
    'RESEARCH_ASSISTANT',
    'TEACHING_ASSISTANT',
    'INSTRUCTOR',
    'SPECIALIST',
    'VISITING_PROFESSOR'
